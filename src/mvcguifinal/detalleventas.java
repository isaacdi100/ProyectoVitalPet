    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {

        detalleventa d = new detalleventa();

        d.setIdVenta(Integer.parseInt(txtIdVenta.getText()));
        d.setIdProducto(Integer.parseInt(txtIdProducto.getText()));
        d.setCantidad(Integer.parseInt(txtCantidad.getText()));
        d.setPrecioUnitario(Double.parseDouble(txtPrecio.getText()));
        d.setSubtotal(Double.parseDouble(txtSubtotal.getText()));

        if (controller.registrarDetalle(d)) {

            JOptionPane.showMessageDialog(this, "Detalle registrado correctamente");

            listarDetalles();
            limpiar();

        } else {

            JOptionPane.showMessageDialog(this, "Error al registrar");

        }
    }
