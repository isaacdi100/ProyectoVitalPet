    public void listarDetalles() {

        modelo.setRowCount(0);

        for (detalleventa d : controller.listarDetalles()) {

            Object[] fila = {
                d.getIdDetalle(),
                d.getIdVenta(),
                d.getIdProducto(),
                d.getCantidad(),
                d.getPrecioUnitario(),
                d.getSubtotal()
            };

            modelo.addRow(fila);
        }
    }

    private void limpiar() {

        txtIdDetalle.setText("");
        txtIdVenta.setText("");
        txtIdProducto.setText("");
        txtCantidad.setText("");
        txtPrecio.setText("");
        txtSubtotal.setText("");
    }
